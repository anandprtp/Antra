from antra.core.engine import DownloadEngine, EngineConfig  # noqa: E402
from antra.core.models import DownloadResult, DownloadStatus, TrackMetadata  # noqa: E402


class _Org:
    root = tmp
    filename_preferences = {}


def engine(**cfg) -> DownloadEngine:
    base = dict(output_format="flac", replaygain=True)
    base.update(cfg)
    return DownloadEngine(resolver=None, organizer=_Org(), config=EngineConfig(**base))


def fresh(name: str, amp: float) -> str:
    return make(os.path.join(tmp, name), f"aevalsrc=exprs={amp}*sin(2*PI*700*t):s=44100", 5, FLAC)


def tm(title: str, album="Alb", total=None, kind="album", playlist=None, album_id=None) -> TrackMetadata:
    return TrackMetadata(title=title, artists=["Art"], album=album, total_tracks=total,
                         request_kind=kind, playlist_name=playlist, album_id=album_id)


import logging  # noqa: E402


class _Capture(logging.Handler):
    def __init__(self):
        super().__init__(logging.DEBUG)
        self.lines: list[str] = []

    def emit(self, record):
        self.lines.append(record.getMessage())


CAP = _Capture()
logging.getLogger("antra.core.engine").addHandler(CAP)
logging.getLogger("antra.core.engine").setLevel(logging.DEBUG)


def run_batch(eng: DownloadEngine, rows: list[tuple[TrackMetadata, str, DownloadStatus]]):
    CAP.lines.clear()
    results = []
    for track, path, status in rows:
        if status == DownloadStatus.COMPLETED:
            eng._apply_track_replaygain(path, track)
        results.append(DownloadResult(track=track, status=status, file_path=path))
    eng._apply_album_replaygain(results)


def album_gain(path: str):
    v = MFLAC(path).get("replaygain_album_gain")
    return v[0] if v else None


def track_gain(path: str):
    v = MFLAC(path).get("replaygain_track_gain")
    return v[0] if v else None


