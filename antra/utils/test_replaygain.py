def make(path: str, lavfi: str, seconds: float, codec_args: list[str]) -> str:
    subprocess.run(
        [FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i", lavfi,
         "-t", str(seconds), "-ac", "2", *codec_args, path],
        check=True,
    )
    return path


def ffmpeg_integrated(path: str) -> float:
    out = subprocess.run(
        [FFMPEG, "-hide_banner", "-nostats", "-i", path, "-af",
         "ebur128=metadata=1,ametadata=mode=print:key=lavfi.r128.I:file=-", "-f", "null", "-"],
        capture_output=True, text=True,
    ).stdout
    return float(out.strip().splitlines()[-1].split("=")[1])


def probe_tags(path: str) -> dict:
    out = subprocess.run(
        [FFPROBE, "-v", "error", "-show_entries", "format_tags:stream_tags", "-of", "json", path],
        capture_output=True, text=True,
    ).stdout
    data = json.loads(out or "{}")
    tags = {}
    for k, v in (data.get("format", {}).get("tags", {}) or {}).items():
        tags[k.upper()] = v
    for s in data.get("streams", []) or []:
        for k, v in (s.get("tags", {}) or {}).items():
            tags.setdefault(k.upper(), v)
    return tags


